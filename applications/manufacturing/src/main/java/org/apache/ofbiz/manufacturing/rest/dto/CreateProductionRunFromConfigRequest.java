package org.apache.ofbiz.manufacturing.rest.dto;

import java.math.BigDecimal;

/**
 * Request DTO for creating a production run from a product configuration
 * via {@code createProductionRunFromConfiguration} service.
 */
public final class CreateProductionRunFromConfigRequest {

    private String facilityId;
    private String configId;
    private BigDecimal quantity;
    private String orderId;
    private String orderItemSeqId;

    public String getFacilityId() {
        return facilityId;
    }

    public void setFacilityId(String facilityId) {
        this.facilityId = facilityId;
    }

    public String getConfigId() {
        return configId;
    }

    public void setConfigId(String configId) {
        this.configId = configId;
    }

    public BigDecimal getQuantity() {
        return quantity;
    }

    public void setQuantity(BigDecimal quantity) {
        this.quantity = quantity;
    }

    public String getOrderId() {
        return orderId;
    }

    public void setOrderId(String orderId) {
        this.orderId = orderId;
    }

    public String getOrderItemSeqId() {
        return orderItemSeqId;
    }

    public void setOrderItemSeqId(String orderItemSeqId) {
        this.orderItemSeqId = orderItemSeqId;
    }
}
